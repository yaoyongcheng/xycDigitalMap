/**
 * 智能电梯轿厢（cage）编号登记表
 *
 * ## 为什么需要这份表
 *
 * 电梯的所有真实数据（在线状态、今日升降次数、累计运行时长、当前楼层/载重/人数）
 * 都在 IOT 网关 `iot.cscec3b-iti.com` 上，而且**按轿厢 sn 查**
 * （V2 `ElevatorRequester` 的 `DeviceSnList` 就是 `ElevatorModel.GetSceneDeviceSnList()`
 * 返回的 `BuildingElevatorCage.sn` 集合）。
 *
 * `:8084` 台账里没有 sn，只有设备名 —— 同塔机那份表的老问题。
 *
 * ## 编号从哪来（不是编的）
 *
 * 2026-11-13 用 UnityPy 解析 V2 场景包
 * `http://120.26.34.95:9689/CDN/PC/v1.0/cb4440f68c48489259d528982c1d7320.bundle`
 * （YooAsset 清单里 `Assets/HotUpdateResources/Scene/MainScene.unity` 对应的包），
 * `MonoBehaviour` 上脚本为 `DigitalMap.Elevator.BuildingElevatorCage` 的节点共 4 个，
 * 各自的 `sn` 字段原样抄下来：
 *
 * | friendlyName | sn |
 * |---|---|
 * | 智能电梯1-1 | 3225122202 |
 * | 智能电梯1-2 | 32251222021 |
 * | 智能电梯2-1 | 32251222023 |
 * | 智能电梯2-2 | E03C1CB9F5011824 |
 *
 * 同一场景里还有 2 个 `BuildingElevator`（friendlyName「智能电梯1」「智能电梯2」，
 * `deviceSn` 都是 `'1'`，不是真实编号）—— 与台账那 2 行**同名同台号**。
 * 也就是说：台账一台「智能电梯N」= 场景里一栋楼的电梯 = **两个轿厢**（双笼）。
 *
 * ## 为什么按台号映射，而不是按名称精确匹配
 *
 * 台账设备名是「智能电梯1」「智能电梯2」，场景轿厢名是「智能电梯1-1」「1-2」。
 * 前缀逐字相同，取名称里第一段数字（`unitNo()`）就能对上 —— 与塔机那份表同法。
 *
 * ## 数据实测（2026-11-13 逐个验证）
 *
 * 4 个编号在网关侧的状态**并不一样**，是逐台查出来的：
 *
 * | sn | 单独查 `queryEvent` | 实际含义 |
 * |---|---|---|
 * | `3225122202` | 正常返回 | 1# 楼主笼，唯一持续上报的一台（工况帧几分钟一条） |
 * | `E03C1CB9F5011824` | `status:0` 空数组 | 网关认这台；最后一次在线 `false` 是 10-21 |
 * | `32251222021` | `status:10 所选设备您无权操作` | 网关**不认**这个编号 |
 * | `32251222023` | 同上 | 网关**不认**这个编号 |
 *
 * 后两个是场景包里字面写着的值（UnityPy 读 `sn` 字段，长度 11，不是解析错位），
 * 但网关侧没有对应设备 —— 要么现场尚未接入，要么场景里填错了号。
 * **混批查询时服务端会静默跳过它们**（200 只带有数据那台的行），所以不会拖累
 * 1-1；单独查一个无效 sn 才回 `status:10`。页面按「—」显示，不拿 0 冒充。
 *
 * 另一个容易误判的点：令牌失效时网关回的是 **HTTP 401 + `status:11 权限不足`**，
 * 看起来像「没有产品权限」，其实只是令牌过期。`api/iot.ts` 已把它规整成 401
 * 并自动重换，不要在业务层把它当权限问题处理。
 */

/** 一个轿厢 */
export interface LiftCage {
  /** 网关设备编号 */
  sn: string
  /** 展示名 —— V2 场景里的 `friendlyName`，原样使用 */
  name: string
  /** 所属台账楼的台号（台账里那一行的 `unitNo()`；设备信息弹层按它找档案） */
  building: number
}

